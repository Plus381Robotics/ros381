def move_to_xy(
    GT,
    x,
    y,
    dir,
    v_max=99.0,
    w_max=99.0,
    d_tol_perc=1.0,
    ang_tol_perc=1.0,
    start_coeff_v=1.0,
    start_coeff_w=1.0,
    stop_coeff_v=1.0,
    stop_coeff_w=1.0,
):
    GT.send_goal(
        1,
        x,
        y,
        0.0,
        dir,
        v_max,
        w_max,
        d_tol_perc,
        ang_tol_perc,
        start_coeff_v,
        start_coeff_w,
        stop_coeff_v,
        stop_coeff_w,
    )
